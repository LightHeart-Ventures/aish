    /// Claim the work package `task` under `scope` for `owner_run`, valid for
    /// `ttl_secs`. Idempotent for the SAME owner (a re-claim just renews).
    ///
    /// Fails LOUDLY when a DIFFERENT run holds a LIVE claim — that error is the
    /// whole point: it is what stops a goal's next turn (a fresh process) from
    /// re-dispatching a work package an earlier wave still has in flight. A
    /// claim is dead — and therefore silently reclaimable — when it was
    /// released, when its TTL lapsed, or when its owner run is terminal
    /// (`done`/`failed`) in `coordinator_runs`.
    pub fn claim_work_package(
        &self,
        scope: &str,
        task: &str,
        owner_run: &str,
        ttl_secs: i64,
    ) -> Result<()> {
        self.claim_keyed(scope, &work_package_key(task), task, owner_run, ttl_secs)
    }

    /// TASK-808: claim the work package for PLAN NODE `node_id` under
    /// `scope_key`, keyed on the node id instead of a fuzzy hash of `task`.
    ///
    /// Same semantics as [`Self::claim_work_package`] — idempotent renewal for
    /// the same owner, loud refusal while a DIFFERENT run holds a live claim,
    /// reclaimable once released / lapsed / owner-terminal — but the identity is
    /// now exact: two nodes with identical briefs no longer contend, and a
    /// re-worded re-dispatch of one node still hits its own lease.
    ///
    /// `task` is still stored on the row: it is the brief the fan-out guard
    /// fuzzy-matches against and what the in-flight directive renders, so the
    /// node id identifies the lease while the text stays human-readable.
    pub fn claim_plan_node(
        &self,
        scope_key: &str,
        node_id: &str,
        task: &str,
        owner_run: &str,
        ttl_secs: i64,
    ) -> Result<()> {
        self.claim_keyed(
            scope_key,
            &plan_node_lease_key(scope_key, node_id),
            task,
            owner_run,
            ttl_secs,
        )
    }

    /// Shared lease body for both key flavours — the conflict check and the
    /// upsert live here ONCE so a text-keyed and a node-keyed claim can never
    /// drift in their liveness or renewal rules.
    fn claim_keyed(
        &self,
        scope: &str,
        key: &str,
        task: &str,
        owner_run: &str,
        ttl_secs: i64,
    ) -> Result<()> {
        let now = unix_now();
        let conn = self.conn.lock().unwrap();
        let tx = conn.unchecked_transaction()?;
        let existing: Option<(String, i64, i64)> = tx
            .query_row(
                "SELECT owner_run, expires_at, released FROM work_package_leases
                 WHERE scope = ?1 AND wp_key = ?2",
                rusqlite::params![scope, key],
                |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?)),
            )
            .optional()?;
        if let Some((holder, expires_at, released)) = existing
            && holder != owner_run
            && released == 0
            && expires_at > now
        {
            let holder_phase: Option<String> = tx
                .query_row(
                    "SELECT phase FROM coordinator_runs WHERE run_id = ?1",
                    rusqlite::params![holder],
                    |r| r.get(0),
                )
                .optional()?;
            let holder_live = !matches!(holder_phase.as_deref(), Some("done") | Some("failed"));
            if holder_live {
                anyhow::bail!(
                    "work package already claimed by run `{holder}` (lease valid for another \
{}s) — do NOT re-dispatch it: monitor that run, `tell` it, or `stop` it first",
                    expires_at - now
                );
            }
        }
        tx.execute(
            "INSERT INTO work_package_leases (scope, wp_key, owner_run, task, expires_at, released)
             VALUES (?1, ?2, ?3, ?4, ?5, 0)
             ON CONFLICT(scope, wp_key) DO UPDATE SET
                 owner_run  = excluded.owner_run,
                 task       = excluded.task,
                 claimed_at = current_timestamp,
                 expires_at = excluded.expires_at,
                 released   = 0",
            rusqlite::params![scope, key, owner_run, task, now + ttl_secs.max(1)],
        )?;
        tx.commit()?;
        Ok(())
    }

